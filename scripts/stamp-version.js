/* Writes src/js/version.js from package.json (version), today's date and the git commit.
   Run before publishing or installing: npm run stamp */
const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const root = path.join(__dirname, '..');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
let commit = 'unknown';
try { commit = execSync('git rev-parse --short HEAD', { cwd: root }).toString().trim(); } catch (e) {}

const now = new Date();
const pad = n => String(n).padStart(2, '0');
const built = now.getFullYear() + '-' + pad(now.getMonth() + 1) + '-' + pad(now.getDate()) +
  ' ' + pad(now.getHours()) + ':' + pad(now.getMinutes());

const out = '/* Generated by scripts/stamp-version.js. Do not edit by hand. */\n' +
  'window.APP_VERSION = ' + JSON.stringify({ version: pkg.version, built: built, commit: commit }) + ';\n';
fs.writeFileSync(path.join(root, 'src', 'js', 'version.js'), out);
console.log('Stamped ' + pkg.version + ' (' + commit + ') ' + built);
